/** Місто за формою місцевого відмінка: «львові» → «Львів» (для голосових команд). */
export const findCityByLocative = (text) => {
  const q = String(text || "").trim().toLowerCase().replace(/[’ʼ`]/g, "'");
  if (!q) return null;
  const hit = Object.entries(CITY_LOCATIVE).find(([, form]) => form.toLowerCase() === q);
  return hit ? hit[0] : null;
};

/** «в Конотопі», «у Львові», «в Одесі» (милозвучність після слова «Погода»). */
export const getCityLocative = (city) => {
  const form = CITY_LOCATIVE[city.name];
  if (!form) return `у місті ${city.name}`;
  return `${/^(в|ф|у|льв|св|тв|хв|зв|дв|сх)/i.test(form) ? "у" : "в"} ${form}`;
};

/**
 * Тексти сторінки міста для Google — ЄДИНЕ джерело для статичних сторінок
 * /pohoda/<slug>/ (vite.config.mjs) і для застосунку (App.jsx), щоб після
 * завантаження JS заголовок не мінявся на інший.
 */
export const getCitySeo = (city) => {
  const inCity = getCityLocative(city);
  // «Конотоп (Сумська обл., Україна)» → «Сумська область, Україна»
  const region = ((city.fullName || "").match(/\(([^)]+)\)/)?.[1] || "Україна").replace(
    /обл\./,
    "область",
  );
  return {
    title: `Погода ${inCity} — прогноз на сьогодні, завтра і 16 днів | Стихія`,
    shortTitle: `Погода ${inCity} | Стихія`,
    heading: `Погода ${inCity}`,
    description: `Погода ${inCity} сьогодні: детальний прогноз для міста ${city.name} (${region}) — температура зараз, погодинно, вітер, опади, УФ-індекс і графіки на 16 днів.`,
    text: `Стихія показує погоду ${inCity} в реальному часі: температуру і як вона відчувається, вологість, тиск, швидкість і пориви вітру, ймовірність опадів, УФ-індекс, схід і захід сонця. Прогноз оновлюється щогодини — погодинно на сьогодні й завтра та по днях на 16 днів уперед.`,
  };
};
