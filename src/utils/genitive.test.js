import { toGenitive } from "./genitive";

describe("toGenitive", () => {
  it.each([
    ["Ваша локація", "вашої локації"],
    ["Ваше місто", "вашого міста"],
    ["Київ", "Києва"],
    ["Харків", "Харкова"],
    ["Львів", "Львова"],
    ["Миколаїв", "Миколаєва"],
    ["Одеса", "Одеси"],
    ["Вінниця", "Вінниці"],
    ["Олександрія", "Олександрії"],
    ["Луцьк", "Луцька"],
    ["Ужгород", "Ужгорода"],
    ["Тернопіль", "Тернополя"],
    ["Дніпро", "Дніпра"],
    ["Чернівці", "Чернівців"],
    ["Суми", "Сум"],
    ["Кривий Ріг", "Кривого Рогу"],
    ["Біла Церква", "Білої Церкви"],
    ["Івано-Франківськ", "Івано-Франківська"],
    ["Токіо", "Токіо"],
    ["Київ, Україна", "Києва, Україна"],
  ])("%s → %s", (input, expected) => {
    expect(toGenitive(input)).toBe(expected);
  });
});
